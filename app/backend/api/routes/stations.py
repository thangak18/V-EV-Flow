from datetime import datetime, timedelta, timezone

from fastapi import APIRouter, Depends, HTTPException, Query

from app.backend.api.dependencies import AppContainer, get_container
from app.backend.contracts.enums import DataType, Scenario
from app.backend.contracts.queue import QueueSnapshotResponse
from app.backend.contracts.stations import StationListResponse

_LOCAL = timezone(timedelta(hours=7))

router = APIRouter()


@router.get("/stations", response_model=StationListResponse, operation_id="listStations")
def list_stations(container: AppContainer = Depends(get_container)) -> StationListResponse:
    data_type = (
        DataType.REAL
        if container.settings.data_backend == "real"
        else DataType.SIMULATED
        if container.settings.data_backend == "file"
        else DataType.MOCK
    )
    return StationListResponse(
        stations=container.stations.list_stations(),
        data_type=data_type,
        source_notes=[
            "Configured station repository; source metadata on each station describes assumptions."
        ],
    )


@router.get(
    "/stations/queue", response_model=QueueSnapshotResponse, operation_id="getStationQueues"
)
def station_queues(
    observed_at: datetime | None = Query(default=None),
    scenario: Scenario = Scenario.NORMAL,
    container: AppContainer = Depends(get_container),
) -> QueueSnapshotResponse:
    """Camera queue views; stations without a camera are left out."""
    at = observed_at if observed_at is not None else datetime.now(_LOCAL)
    if at.tzinfo is None or at.utcoffset() is None:
        raise HTTPException(422, "observed_at must be timezone-aware")
    source = container.queue_source
    if source is None:
        return QueueSnapshotResponse(
            observed_at=at,
            scenario=scenario,
            observations=(),
            data_type=DataType.MOCK,
            source_notes=["Station camera queue data is disabled (CAMERA_QUEUE_BACKEND=off)."],
        )
    views = (
        source.observe(station.station_id, at, scenario)
        for station in container.stations.list_stations()
    )
    return QueueSnapshotResponse(
        observed_at=at,
        scenario=scenario,
        observations=tuple(view for view in views if view is not None),
        data_type=DataType.MOCK,
        source_notes=[
            "Mock camera output: counts are generated by time of day and scenario, "
            "not read from video. Stations without a camera are omitted."
        ],
    )
